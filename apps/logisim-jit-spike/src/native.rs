use super::{Operand, Region, Word};
use cranelift_codegen::{
    Context,
    ir::{
        AbiParam, Function, InstBuilder, MemFlags, Signature, Value,
        types::{I32, I64},
    },
    isa::{self, CallConv},
    settings::{self, Configurable},
};
use cranelift_frontend::{FunctionBuilder, FunctionBuilderContext};
use memmap2::{Mmap, MmapMut};

pub struct Code {
    image: Mmap,
    words: usize,
}

impl Code {
    pub fn compile(region: &Region) -> Result<Self, String> {
        Self::compile_with(region, MmapMut::map_anon)
    }

    fn compile_with(
        region: &Region,
        allocate: impl FnOnce(usize) -> std::io::Result<MmapMut>,
    ) -> Result<Self, String> {
        let words = region.frame_len()?;
        let mut flags = settings::builder();
        flags.set("opt_level", "speed").map_err(|e| e.to_string())?;
        flags
            .set("enable_verifier", "true")
            .map_err(|e| e.to_string())?;
        let isa = isa::lookup_by_name("x86_64-unknown-linux-gnu")
            .map_err(|e| e.to_string())?
            .finish(settings::Flags::new(flags))
            .map_err(|e| e.to_string())?;
        let mut signature = Signature::new(CallConv::SystemV);
        signature.params.push(AbiParam::new(I64));
        let mut context =
            Context::for_function(Function::with_name_signature(Default::default(), signature));
        let mut scratch = FunctionBuilderContext::new();
        let mut b = FunctionBuilder::new(&mut context.func, &mut scratch);
        let block = b.create_block();
        b.append_block_params_for_function_params(block);
        b.switch_to_block(block);
        b.seal_block(block);
        let frame = b.block_params(block)[0];
        match region {
            Region::Unary { width, invert } => {
                let mut v = load(&mut b, frame, 0);
                for (i, &inverse) in invert.iter().enumerate() {
                    if inverse {
                        let bad = b.ins().bor(v[1], v[2]);
                        let occupied = b.ins().bor(v[0], bad);
                        let ones = b.ins().bxor_imm(occupied, mask(*width));
                        v = [ones, b.ins().iconst(I32, 0), bad];
                    }
                    store(&mut b, frame, i + 1, v);
                }
            }
            Region::Add { width, operands } => add(&mut b, frame, *width, operands),
        }
        b.ins().return_(&[]);
        b.finalize();
        let compiled = context
            .compile(&*isa, &mut Default::default())
            .map_err(|e| format!("{e:?}"))?;
        if !compiled.buffer.relocs().is_empty() || !compiled.buffer.traps().is_empty() {
            return Err("Region requires relocation or a trap handler".into());
        }
        let bytes = compiled.code_buffer();
        if bytes.is_empty() || bytes.len() > 256 * 1024 {
            return Err("Region exceeds executable image budget".into());
        }
        let mut writable = allocate(bytes.len()).map_err(|e| e.to_string())?;
        writable.copy_from_slice(bytes);
        let image = writable.make_exec().map_err(|e| e.to_string())?;
        Ok(Self { image, words })
    }

    /// No code address escapes this owner. Only call with initialized frame words.
    #[allow(unsafe_code)]
    pub fn run(&self, frame: &mut [Word]) {
        assert_eq!(frame.len(), self.words);
        // SAFETY: on Linux x86-64 the sole entry has the System V signature void(Word*).
        // The closed IR above emits only straight-line integer ops and constant frame
        // offsets bounded by Region::frame_len(). No guest pointers, indirect branches,
        // relocations, calls or trap sites. The exclusive slice is live for the call.
        // make_exec consumes the only writable handle; x86 instruction caches are coherent.
        unsafe {
            let entry: unsafe extern "C" fn(*mut Word) = std::mem::transmute(self.image.as_ptr());
            entry(frame.as_mut_ptr());
        }
    }
}

fn mask(width: u8) -> i64 {
    i64::from(u32::MAX >> (32 - width))
}

// Word is [u32; 3]. All indices are generated by the bounded IR lowering,
// so each 4-byte load/store is aligned and inside the checked frame.
fn offset(word: usize, plane: usize) -> i32 {
    ((3 * word + plane) * 4) as i32
}

fn load(b: &mut FunctionBuilder<'_>, frame: Value, word: usize) -> [Value; 3] {
    std::array::from_fn(|plane| {
        b.ins()
            .load(I32, MemFlags::trusted(), frame, offset(word, plane))
    })
}

fn store(b: &mut FunctionBuilder<'_>, frame: Value, word: usize, v: [Value; 3]) {
    for (plane, part) in v.into_iter().enumerate() {
        b.ins()
            .store(MemFlags::trusted(), part, frame, offset(word, plane));
    }
}

fn add(b: &mut FunctionBuilder<'_>, frame: Value, width: u8, operands: &[Operand; 3]) {
    let [a, rhs, cin] = std::array::from_fn(|i| match operands[i] {
        Operand::Input => load(b, frame, i),
        Operand::Constant(planes) => planes.map(|p| b.ins().iconst(I32, i64::from(p))),
    });
    // The first uncertain column determines the entire remaining carry chain.
    // An undriven carry-in is zero; an erroneous carry-in poisons every column.
    let error = b.ins().bor(a[2], rhs[2]);
    let error = b.ins().bor(error, cin[2]);
    let unknown = b.ins().bor(a[1], rhs[1]);
    let bad = b.ins().bor(error, unknown);
    let neg = b.ins().ineg(bad);
    let first = b.ins().band(bad, neg);
    let tail = b.ins().ineg(first);
    let tail = b.ins().band_imm(tail, mask(width));
    let is_error = b.ins().band(first, error);
    let zero = b.ins().iconst(I32, 0);
    let errors = b.ins().select(is_error, tail, zero);
    let unknowns = b.ins().bxor(tail, errors);
    let a64 = b.ins().uextend(I64, a[0]);
    let b64 = b.ins().uextend(I64, rhs[0]);
    let c64 = b.ins().uextend(I64, cin[0]);
    let sum = b.ins().iadd(a64, b64);
    let sum = b.ins().iadd(sum, c64);
    let low = b.ins().ireduce(I32, sum);
    let known = b.ins().bxor_imm(tail, mask(width));
    let ones = b.ins().band(low, known);
    store(b, frame, 3, [ones, unknowns, errors]);
    let carry = b.ins().ushr_imm(sum, i64::from(width));
    let carry = b.ins().ireduce(I32, carry);
    let carry = b.ins().select(bad, zero, carry);
    let ux = b.ins().ushr_imm(unknowns, i64::from(width - 1));
    let ex = b.ins().ushr_imm(errors, i64::from(width - 1));
    store(b, frame, 4, [carry, ux, ex]);
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn addition_keeps_the_first_uncertain_column_and_carry_out() {
        let code = Code::compile(&Region::Add {
            width: 32,
            operands: [Operand::Input, Operand::Input, Operand::Constant([0, 1, 0])],
        })
        .unwrap();
        for (left, right, sum, carry) in [
            ([u32::MAX, 0, 0], [1, 0, 0], [0; 3], [1, 0, 0]),
            ([1, 2, 0], [1, 0, 4], [0, !1, 0], [0, 1, 0]),
            ([1, 4, 0], [1, 0, 2], [0, 0, !1], [0, 0, 1]),
        ] {
            let mut frame = [left, right, [0; 3], [0; 3], [0; 3]];
            code.run(&mut frame);
            assert_eq!(&frame[3..], &[sum, carry]);
        }
    }

    #[test]
    fn bounds_and_executable_allocation_failure() {
        let mut plan = Region::Unary {
            width: 32,
            invert: vec![true; 129],
        };
        assert!(Code::compile(&plan).is_err());
        plan = Region::Unary {
            width: 32,
            invert: vec![true, false],
        };
        assert!(
            Code::compile_with(&plan, |_| Err(std::io::ErrorKind::OutOfMemory.into())).is_err()
        );
        let code = Code::compile(&plan).unwrap();
        let mut words = [[1, 2, 4], [0; 3], [0; 3]];
        code.run(&mut words);
        assert_eq!(words[1], [!7, 0, 6]);
        assert_eq!(words[2], words[1]);
    }
}
